#!/usr/bin/env node
// build-lineage-widget.mjs — regenerate Assets/lineage-timeline.html from the
// MetaMedium whitepaper's "The Lineage" timeline.
//
//   node scripts/build-lineage-widget.mjs [path/to/MetaMedium/index.html]
//
// Default input: ../MetaMedium/index.html relative to this repo (the sibling
// checkout at ~/Documents/github/MetaMedium). The widget is fully
// self-contained: data inlined as JSON, theme read from ?theme=, tokens
// aliased from styles/jh-chrome.css (never restated). Re-run whenever the
// whitepaper timeline changes; the artifact is committed.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = process.argv[2] || resolve(root, '../MetaMedium/index.html');
const output = resolve(root, 'Assets/lineage-timeline.html');

const html = readFileSync(input, 'utf8');
const block = html.match(/<div class="timeline-single" id="timelineSingle">([\s\S]*?)\n<\/div>\n\n\n        <\/section>/);
if (!block) { console.error('timeline block not found in ' + input); process.exit(1); }

const clean = (s) => s.replace(/<[^>]+>/g, '').trim();
const entries = [];
const re = /<div class="tl-entry( tl-hidden)?(?: tl-convergence)?">\s*<div class="tl-year">(\d+)<\/div>[\s\S]*?<div class="tl-title">(.*?) <span class="tl-badge (\w+)">([^<]+)<\/span><\/div>\s*<div class="tl-author">(.*?)<\/div>([\s\S]*?)(?=<\/div>\s*<\/div>)/g;
let m;
while ((m = re.exec(block[1])) !== null) {
  const inner = m[7];
  const desc = ((inner.match(/<div class="tl-desc">(.*?)<\/div>/) || [])[1] || '').replace(/<[^>]+>/g, '').trim();
  const sig = ((inner.match(/<div class="tl-sig">([^<]*)/) || [])[1] || '').replace(/^┗━━ /, '').trim();
  const synth = (inner.match(/<div class="tl-synthesis">[\s\S]*?<ul>([\s\S]*?)<\/ul>/) || [])[1];
  const synthesis = synth
    ? [...synth.matchAll(/<li>([\s\S]*?)<\/li>/g)].map((li) => clean(li[1]))
    : [];
  entries.push({
    year: m[2], title: clean(m[3]), badge: m[5], author: clean(m[6]),
    desc, sig, synthesis, hidden: !!m[1],
  });
}
if (entries.length < 20) { console.error('suspiciously few entries extracted: ' + entries.length); process.exit(1); }

